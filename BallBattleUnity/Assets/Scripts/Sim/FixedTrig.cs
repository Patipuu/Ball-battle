        public static float SinDeg(float degrees) => SinAtIndex(ToIndex(degrees));
        public static float CosDeg(float degrees) => SinAtIndex((ToIndex(degrees) + QuarterSteps) % FullSteps);

        static int ToIndex(float degrees)
        {
            if (float.IsNaN(degrees) || float.IsInfinity(degrees))
                throw new ArgumentOutOfRangeException(nameof(degrees));
            var steps = (degrees * 10f) % FullSteps;
            if (steps < 0f) steps += FullSteps;
            var index = (int)(steps + 0.5f);
            return index == FullSteps ? 0 : index;
        }

        static float SinAtIndex(int index)
        {
            var quadrant = index / QuarterSteps;
            var remainder = index % QuarterSteps;
            if (remainder == 0 && (quadrant == 0 || quadrant == 2)) return 0f;
            switch (quadrant)
            {
                case 0: return Value(remainder);
                case 1: return Value(QuarterSteps - remainder);
                case 2: return -Value(remainder);
                default: return -Value(QuarterSteps - remainder);
            }
        }

        static float Value(int index) => BitConverter.Int32BitsToSingle(unchecked((int)QuarterSinBits[index]));
